/**
 * Calculates wellness score from question choices
 * @param selectedOptions Map of questionId -> optionIndex
 */
export function calculateWellnessScore(
  selectedOptions: Record<string, number>
): AssessmentResult {
  let totalScore = 0;
  const recommendations: string[] = [];

  CALCULATOR_QUESTIONS.forEach((q) => {
    const selectedIdx = selectedOptions[q.id];
    if (selectedIdx !== undefined && q.options[selectedIdx]) {
      const opt = q.options[selectedIdx];
      totalScore += opt.points;
      if (opt.points <= 12) {
        recommendations.push(opt.tip);
      }
    }
  });

  // Clamp 0 - 100
  totalScore = Math.max(0, Math.min(100, totalScore));

  if (totalScore >= 80) {
    return {
      score: totalScore,
      tier: 'low',
      tierLabel: 'Маш сайн зуршилтай (Эрсдэл бага)',
      tierColor: 'emerald',
      summary: 'Таны нүдний эрүүл мэндийн өдөр тутмын зуршил, хамгаалалт сайн түвшинд байна. Энэхүү дадлаа хадгалж, жил бүр урьдчилан сэргийлэх үзлэгт хамрагдаарай.',
      recommendations: recommendations.length > 0
        ? recommendations
        : ['Жилд 1 удаа тогтмол урьдчилан сэргийлэх үзлэгт хамрагдаж хараагаа хянаарай.']
    };
  } else if (totalScore >= 50) {
    return {
      score: totalScore,
      tier: 'moderate',
      tierLabel: 'Дунд зэргийн ачаалалтай (Анхаарах шаардлагатай)',
      tierColor: 'amber',
      summary: 'Таны нүдэнд дижитал дэлгэц болон гадны хүчин зүйлсийн дунд зэргийн ачаалал үүсэж байна. Цаашид хараа муудахаас сэргийлж зөвлөмжүүдийг мөрдөөрэй.',
      recommendations: recommendations.length > 0
        ? recommendations
        : ['20-20-20 дүрмийг баримталж, консервантгүй хиймэл нулимс хэрэглэхийг зөвлөж байна.']
    };
  } else {
    return {
      score: totalScore,
      tier: 'high',
      tierLabel: 'Нүдний өндөр ачаалалтай (Эмчид үзүүлэхийг зөвлөж байна)',
      tierColor: 'rose',
      summary: 'Таны нүд байнгын өндөр ачаалалтай, хуурайшилт болон ядралт үүсэх өндөр эрсдэлтэй байна. Цаг алдалгүй нарийн мэргэжлийн нүдний эмчид үзүүлж оношилгоо хийлгэнэ үү.',
      recommendations: recommendations.length > 0
        ? recommendations
        : [
            'Цаг алдалгүй нарийн мэргэжлийн нүдний эмчид үзүүлж, харааны чадал болон нүдний даралтаа хэмжүүлэх.',
            'Дэлгэцийн цагаа багасгах, 20 минут тутамд нүдээ заавал амраах.'
          ]
    };
  }
}
